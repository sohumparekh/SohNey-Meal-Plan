// Validates the seed library, generates the 4-week rotation and writes a review document.
// Run: npx tsx scripts/gen-rotation.ts
import { writeFileSync } from "node:fs";
import { DISHES, DISH_BY_ID, type Dish } from "../src/lib/seed/dishes";
import { INGREDIENT_BY_ID } from "../src/lib/seed/ingredients";
import {
  generateRotation, scorePlan, FAVOURITES, perishables, windowFor, WEEK_DAYS, DEFAULT_CONFIG, isStreet,
} from "../src/lib/planner/rotation";

// ---------- validation ----------
const errors: string[] = [];
for (const d of DISHES) {
  for (const i of d.ingredients) if (!INGREDIENT_BY_ID[i.ingredientId]) errors.push(`${d.id}: unknown ingredient ${i.ingredientId}`);
  const pb = DISH_BY_ID[d.planBId];
  if (!pb) { errors.push(`${d.id}: unknown plan B ${d.planBId}`); continue; }
  if (pb.id === d.id) errors.push(`${d.id}: plan B is itself`);
  if (!d.slots.some((s) => pb.slots.includes(s))) errors.push(`${d.id}: plan B ${pb.id} shares no meal slot`);
  const fresh = perishables(pb).map((i) => i.ingredientId);
  if (fresh.length) errors.push(`${d.id}: plan B ${pb.id} needs non-staples: ${fresh.join(", ")}`);
  if (pb.prepAhead) errors.push(`${d.id}: plan B ${pb.id} needs prep-ahead`);
}
const ids = new Set<string>();
for (const d of DISHES) { if (ids.has(d.id)) errors.push(`duplicate dish ${d.id}`); ids.add(d.id); }
for (const f of FAVOURITES) if (!DISH_BY_ID[f]) errors.push(`unknown favourite ${f}`);
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }

// ---------- generate ----------
const t0 = Date.now();
const { plan, score } = generateRotation(DEFAULT_CONFIG);
console.log(`generated in ${Date.now() - t0} ms, hard violations: ${score.hard}, soft score: ${score.total}`);
console.log(JSON.stringify(score.parts));

// ---------- render ----------
const out: string[] = [];
const slotCount = (s: string) => DISHES.filter((d) => d.slots.includes(s as never)).length;
out.push(`# Dish library and 4-week rotation (draft for review)\n`);
out.push(`Generated by \`scripts/gen-rotation.ts\`. ${DISHES.length} dishes. Hard-rule violations: **${score.hard}**.\n`);
out.push(`## Library by slot and cuisine\n`);
const cuisines = [...new Set(DISHES.map((d) => d.cuisine))];
out.push(`| Cuisine | Breakfast | Lunch | Dinner | Total dishes |`);
out.push(`|---|---|---|---|---|`);
for (const c of cuisines) {
  const ds = DISHES.filter((d) => d.cuisine === c);
  const n = (s: string) => ds.filter((d) => d.slots.includes(s as never)).length;
  out.push(`| ${c} | ${n("breakfast")} | ${n("lunch")} | ${n("dinner")} | ${ds.length} |`);
}
out.push(`| **All** | **${slotCount("breakfast")}** | **${slotCount("lunch")}** | **${slotCount("dinner")}** | **${DISHES.length}** |\n`);
out.push(`Dishes eligible for more than one slot are counted in each. Effort: ` +
  ["quick", "medium", "long"].map((e) => `${e} ${DISHES.filter((d) => d.effort === e).length}`).join(", ") +
  `. Need prep the day before: ${DISHES.filter((d) => d.prepAhead).length}.\n`);

out.push(`## Full library\n`);
out.push(`| Dish | Cook calls it | Slots | Cuisine | Effort | Prep ahead | Plan B |`);
out.push(`|---|---|---|---|---|---|---|`);
for (const d of DISHES)
  out.push(`| ${d.nameEn} | ${d.nameCook} | ${d.slots.map((s) => s[0].toUpperCase()).join("")} | ${d.cuisine} | ${d.effort} | ${d.prepAhead ? d.prepAhead.leadHours + "h" : ""} | ${DISH_BY_ID[d.planBId].nameEn} |`);

out.push(`\n## 4-week rotation\n`);
out.push(`Week runs **Saturday to Friday** (weekly bag reaches home Friday night). ★ = needs prep the day before. ⓣ = uses an item from the Tuesday top-up.\n`);
const label = (d: Dish, day: number) => {
  const usesTopup = perishables(d).some((i) => windowFor(i.ingredientId, day) === "topup");
  return `${d.nameEn}${d.prepAhead ? " ★" : ""}${usesTopup ? " ⓣ" : ""}`;
};
for (let w = 0; w < 4; w++) {
  out.push(`### Week ${w + 1}\n`);
  out.push(`| Day | Breakfast | Lunch | Dinner |`);
  out.push(`|---|---|---|---|`);
  const topup = new Set<string>();
  for (let i = 0; i < 7; i++) {
    const day = w * 7 + i;
    const [b, l, dn] = plan[day].map((id) => DISH_BY_ID[id]);
    out.push(`| ${WEEK_DAYS[i]} | ${label(b, day)} | ${label(l, day)} | ${label(dn, day)}${isStreet(dn) ? " 🌶" : ""} |`);
    for (const d of [b, l, dn]) for (const ing of perishables(d)) if (windowFor(ing.ingredientId, day) === "topup") topup.add(INGREDIENT_BY_ID[ing.ingredientId].nameEn);
  }
  out.push(`\nTop-up needed: ${topup.size ? [...topup].join(", ") : "none"}\n`);
}
writeFileSync("docs/rotation-draft.md", out.join("\n"));
writeFileSync("src/lib/seed/rotation.json", JSON.stringify(plan, null, 0));
console.log("check:", scorePlan(plan, DEFAULT_CONFIG).hard);
